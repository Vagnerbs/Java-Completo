package entities.enums;

// Enum é um tipo especial de classe em Java que representa um conjunto fixo de constantes.
// Ele é usado quando temos valores pré-definidos que não mudam, tornando o código mais legível e seguro.
public enum WorkerLevel {

    // Constantes que representam os níveis de um trabalhador
    JUNIOR,     // Nível inicial, geralmente menos experiência
    MID_LEVEL,  // Nível intermediário, experiência moderada
    SENIOR;     // Nível avançado, muita experiência e responsabilidade
}
